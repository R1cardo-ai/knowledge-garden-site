import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const js=ts.transpile(readFileSync('lib/note-blocks.ts','utf8'),{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2017});
const {noteBlocks,noteInline}=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
assert.deepEqual(noteBlocks(''),[]);
assert.deepEqual(noteBlocks('旧笔记\r\n保留换行').map(b=>b.text),['旧笔记\n保留换行']);
const blocks=noteBlocks('# 第一章\n正文\n\n## 第二章\n<script>test</script>');
assert.deepEqual(blocks.map(b=>b.level),[2,0,3,0]);
assert.equal(blocks[3].text,'<script>test</script>');
assert.equal(new Set(blocks.map(b=>b.id)).size,blocks.length);
assert.deepEqual(noteBlocks('普通文字 # 不作为标题').map(b=>b.level),[0]);
console.log('Notes compatibility checks passed: plain text, line endings, real headings, unique anchors, literal HTML.');

const fenced = noteBlocks('# 开始\n正文\n\n```js\n# not a heading\n\nconst x = "<script>";\n```\n\n## 结束');
assert.deepEqual(fenced.map(block=>block.level),[2,0,0,3]);
assert.equal(fenced[2].kind,'code');
assert.equal(fenced[2].text,'# not a heading\n\nconst x = "<script>";');
assert.equal(fenced[2].language,'js');
assert.equal(noteBlocks('```js\n未闭合')[0].text,'```js\n未闭合');
assert.equal(noteBlocks('```\n```')[0].kind,'code');
assert.deepEqual(noteInline('[危险](javascript:alert(1))'),[{text:'[危险](javascript:alert(1))'}]);
assert.deepEqual(noteInline('<script>x</script>'),[{text:'<script>x</script>'}]);
assert.equal(noteInline('看 [说明](https://example.com/a?q=1&b=2)')[1].href,'https://example.com/a?q=1&b=2');
assert.equal(noteInline('![作品说明](https://example.com/proof.png)')[0].image,true);
assert.equal(noteInline('链接 https://example.com/。')[1].href,'https://example.com/');
console.log('Reader boundaries passed: closed fences, literal HTML, blank code lines, unfinished fences, HTTP links, images and unsafe link rejection.');
assert.deepEqual(noteBlocks('```js\n# literal heading\n\ntext').map(block=>block.level),[0]);
assert.equal(noteBlocks('```js\n# literal heading\n\ntext')[0].text,'```js\n# literal heading\n\ntext');
