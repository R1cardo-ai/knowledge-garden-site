"""Split the Garden Serif SC CJK faces into unicode-range tiers.

The full faces are ~3.4 MB each and sat in front of every essay. Browsers fetch a
face when one of its glyphs is used, so slicing by character frequency lets a
normal page download only the common tier instead of the whole font.

Source faces live in assets/fonts (not served). Generated slices and the shared
@font-face sheet live in public/fonts. Re-run after replacing a source face:

    python scripts/build-fonts.py
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

from fontTools.ttLib import TTFont
from wordfreq import top_n_list

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "fonts"
OUTPUT = ROOT / "public" / "fonts"
FACES = [
    ("GardenSerifSC-Regular.woff2", "GardenSerifSC-Regular", "400"),
    ("GardenSerifSC-SemiBold.woff2", "GardenSerifSC-SemiBold", "600 900"),
]
# Character tiers by frequency rank. A typical essay lives in tiers 1-2; rare
# characters fall through to the system serif instead of downloading everything.
TIERS = [(0, 300), (300, 1000), (1000, 2200), (2200, 3500)]
COMMON_EXTRA = (
    [chr(code) for code in range(0x20, 0x7F)]
    + [chr(code) for code in range(0x3000, 0x3040)]
    + [chr(code) for code in range(0xFF00, 0xFFF0)]
)


def unicode_range(characters: str) -> str:
    codes = sorted({ord(char) for char in characters})
    if not codes:
        return ""
    parts: list[str] = []
    start = previous = codes[0]
    for code in codes[1:]:
        if code == previous + 1:
            previous = code
            continue
        parts.append(f"U+{start:X}" if start == previous else f"U+{start:X}-{previous:X}")
        start = previous = code
    parts.append(f"U+{start:X}" if start == previous else f"U+{start:X}-{previous:X}")
    return ",".join(parts)


def main() -> None:
    regular = TTFont(SOURCE / FACES[0][0])
    cmap = set(regular.getBestCmap())
    ranked: list[str] = []
    seen: set[str] = set()
    for word in top_n_list("zh", 60000):
        for char in word:
            if char in seen or ord(char) not in cmap:
                continue
            seen.add(char)
            ranked.append(char)
    # Keep the CJK tiers separate from the Latin/punctuation face so a page with
    # only headings does not pull a Chinese tier.
    cjk = [char for char in ranked if 0x3400 <= ord(char) <= 0x9FFF]
    extras = "".join(char for char in COMMON_EXTRA if ord(char) in cmap)
    tiers: list[tuple[str, list[str]]] = []
    for index, (start, end) in enumerate(TIERS, start=1):
        characters = cjk[start:end]
        if characters:
            tiers.append((f"cjk-{index}", characters))
    if extras:
        tiers.insert(0, ("latin", list(extras)))

    OUTPUT.mkdir(parents=True, exist_ok=True)
    css: list[str] = ["/* Generated by scripts/build-fonts.py. Do not edit by hand. */"]
    total = 0
    for source_name, output_name, weight in FACES:
        source = SOURCE / source_name
        for tier_name, characters in tiers:
            text = "".join(characters)
            target = OUTPUT / f"{output_name}-{tier_name}.woff2"
            with tempfile.NamedTemporaryFile("w", suffix=".txt", encoding="utf-8", delete=False) as handle:
                handle.write(text)
                text_path = Path(handle.name)
            try:
                subprocess.run(
                    [
                        sys.executable,
                        "-m",
                        "fontTools.subset",
                        str(source),
                        f"--text-file={text_path}",
                        "--flavor=woff2",
                        "--layout-features=*",
                        f"--output-file={target}",
                    ],
                    check=True,
                    stdout=subprocess.DEVNULL,
                )
            finally:
                text_path.unlink(missing_ok=True)
            total += target.stat().st_size
            css.append(
                "@font-face{"
                "font-family:'Garden Serif SC';font-style:normal;"
                f"font-weight:{weight};font-display:swap;"
                f"src:url('{target.name}') format('woff2');"
                f"unicode-range:{unicode_range(text)};"
                "}"
            )
            print(f"{target.name}: {target.stat().st_size / 1024:.0f} KB / {len(characters)} chars")

    (OUTPUT / "garden-serif.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    print(f"Total slices: {total / 1024 / 1024:.2f} MB; CSS: {(OUTPUT / 'garden-serif.css').stat().st_size / 1024:.0f} KB")


if __name__ == "__main__":
    main()
